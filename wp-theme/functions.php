			btn.addEventListener('click', function () {
				btn.disabled = true;
				var stalls = 0;
				(function next(lastLeft) {
					var body = new FormData();
					body.append('action', 'teg_copy_assets');
					body.append('_ajax_nonce', btn.dataset.nonce);
